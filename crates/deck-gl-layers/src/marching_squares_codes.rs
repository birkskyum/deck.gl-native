//! Marching squares lookup tables, generated from deck.gl's
//! `aggregation-layers/src/contour-layer/marching-squares-codes.ts`. Offsets are relative to
//! the reference vertex at the top right of the cell being processed, in cell units.

/// Two end points of an isoline segment
pub type Segment = [[f64; 2]; 2];

/// Segments for one isoline code; saddle cases pick by the mean code (0 or 1).
pub enum LineCase {
    Fixed(&'static [Segment]),
    Saddle([&'static [Segment]; 2]),
}

/// Polygons for one isoband code; saddle cases pick by the mean code (0, 1 or 2).
pub enum BandCase {
    Fixed(&'static [&'static [[f64; 2]]]),
    Saddle([&'static [&'static [[f64; 2]]]; 3]),
}

